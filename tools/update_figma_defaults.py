#!/usr/bin/env python3
"""Generate compile-time Figma defaults from the checked-in design snapshot."""

import argparse
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
SOURCE = ROOT / "catalog/figma-lvui-components.json"
OUTPUT = ROOT / "src/Compiler/FigmaDefaults.def"


def cpp_string(value):
    # Octal UTF-8 escapes avoid depending on the compiler's source encoding and
    # cannot consume a following digit, unlike a variable-length hex escape.
    result = '"'
    for byte in value.encode("utf-8"):
        if byte in (34, 92):
            result += "\\" + chr(byte)
        elif 32 <= byte <= 126:
            result += chr(byte)
        else:
            result += "\\%03o" % byte
    return result + '"'


def render(snapshot):
    if snapshot.get("schema") != 1 or not isinstance(snapshot.get("pages"), list):
        raise ValueError("Invalid Figma snapshot")
    references = {item["id"]: item["name"] for item in snapshot.get("references", [])}
    records = {}
    for page in snapshot["pages"]:
        for component in page["components"]:
            for raw_name, prop in component["properties"].items():
                name = raw_name.split("#", 1)[0]
                key = (component["id"], name)
                value = prop["defaultValue"]
                if key in records or prop["type"] not in {"TEXT", "BOOLEAN", "VARIANT", "INSTANCE_SWAP"}:
                    raise ValueError(f"Invalid or duplicate Figma property: {key}")
                if prop["type"] == "VARIANT" and value not in prop.get("variantOptions", []):
                    raise ValueError(f"Default is not a Figma variant: {key}")
                if prop["type"] == "INSTANCE_SWAP":
                    if value not in references or references[value] is None:
                        raise ValueError(f"Unresolved Figma instance default: {key}")
                    value = references[value]
                elif isinstance(value, bool):
                    value = "true" if value else "false"
                elif not isinstance(value, str):
                    raise ValueError(f"Unsupported Figma default: {key}")
                records[key] = value
    lines = ["// Generated by tools/update_figma_defaults.py from catalog/figma-lvui-components.json."]
    lines.extend("LVUI_FIGMA_DEFAULT(%s, %s, %s)" % tuple(map(cpp_string, (node, name, value)))
                 for (node, name), value in sorted(records.items()))
    return "\n".join(lines) + "\n"


def main():
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    generated = render(json.loads(SOURCE.read_text(encoding="utf-8")))
    if args.check:
        if not OUTPUT.exists() or OUTPUT.read_text(encoding="utf-8") != generated:
            raise SystemExit("Figma defaults are stale")
    else:
        OUTPUT.write_text(generated, encoding="utf-8")
    print("Figma default catalog verified" if args.check else "Figma default catalog updated")


if __name__ == "__main__":
    main()
